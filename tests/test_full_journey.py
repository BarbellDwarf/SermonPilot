"""End-to-end dry-run journey: process, review, apply, metadata, no upload.

The media is a short synthetic video generated by ffmpeg in the test's temp
directory. No network, model, or SermonAudio call is allowed: transcription,
cut detection, and description generation are stubbed, and the API create and
upload functions raise if touched.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path
from unittest.mock import Mock

import pytest

import sermon_updater as su
from src.auto_edit import EditPlan, kept_transcript_spans
from ui.auto_edit_apply import run_library_apply
from ui.database import SermonDatabase, SermonRepository

SEGMENTS = [
    {"start": 0.0, "end": 5.0, "text": "before the window"},
    {"start": 5.0, "end": 20.0, "text": "opening teaching"},
    {"start": 20.0, "end": 30.0, "text": "REMOVED SENTINEL aside"},
    {"start": 30.0, "end": 55.0, "text": "closing teaching"},
    {"start": 55.0, "end": 60.0, "text": "after the window"},
]
PLAN = EditPlan(
    start=5.0,
    end=55.0,
    confidence=0.95,
    needs_review=False,
    evidence="synthetic",
    remove_segments=[{"start_sec": 20.0, "end_sec": 30.0}],
)
KEPT_TEXT = "opening teaching closing teaching"


def _make_video(path: Path) -> None:
    subprocess.run(
        [
            "ffmpeg", "-y",
            "-f", "lavfi", "-i", "testsrc=size=320x240:rate=24",
            "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=16000",
            "-t", "60",
            "-c:v", "libx264", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-shortest", str(path),
        ],
        check=True,
        capture_output=True,
    )


def _duration(path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "quiet", "-print_format", "json", "-show_format", str(path)],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return float(json.loads(out)["format"]["duration"])


def test_dry_run_journey_process_review_apply(tmp_path: Path, monkeypatch) -> None:
    if shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None:
        pytest.skip("ffmpeg/ffprobe not installed")

    db_path = tmp_path / "journey.db"
    output_root = tmp_path / "output"
    monkeypatch.setenv("DATABASE_URL", str(db_path))
    monkeypatch.setenv("SERMONPILOT_DB", str(db_path))
    db = SermonDatabase(db_path=str(db_path))
    db.init_database()
    monkeypatch.setattr("ui.database._db", db)
    repo = SermonRepository(db)

    video = tmp_path / "teaching.mp4"
    _make_video(video)

    seen_transcript: dict[str, str] = {}

    def fake_summary(transcript: str, *args, **kwargs) -> str:
        seen_transcript["description"] = transcript
        return "Sentinel description."

    create_api = Mock(side_effect=AssertionError("dry run must not create on SermonAudio"))
    upload = Mock(side_effect=AssertionError("dry run must not upload to SermonAudio"))
    monkeypatch.setattr(su, "transcribe_segments", Mock(return_value=SEGMENTS))
    monkeypatch.setattr(su, "detect_cut_points", Mock(return_value=PLAN))
    monkeypatch.setattr(su, "generate_summary", fake_summary)
    monkeypatch.setattr(su, "create_new_sermon_api", create_api)
    monkeypatch.setattr(su, "upload_media_file", upload)

    config = {
        "output_directory": str(output_root),
        "auto_edit": {"enabled": False, "min_sermon_seconds": 1, "qa_margin_seconds": 3.0},
        "av_sync": {"enabled": False},
        "audio_enhancement_method": "none",
    }

    created = su.process_new_sermon(
        str(video),
        speaker_name="Journey Speaker",
        recorded_date="2026-01-02",
        title="Journey Teaching",
        hashtags="#journey",
        dry_run=True,
        skip_audio=True,
        skip_ai_generation=True,
        auto_edit_mode="interactive",
        config=config,
    )
    assert created["success"] is True, created.get("error")
    assert created["edit_plan_status"] == "pending_review"
    sermon_id = created["sermon_id"]

    plan_row = repo.get_current_edit_plan(sermon_id)
    assert plan_row is not None
    remove_segments = plan_row["remove_segments"]
    if isinstance(remove_segments, str):
        remove_segments = json.loads(remove_segments)

    applied = run_library_apply(
        repo,
        sermon_id,
        start=plan_row["proposed_start"],
        end=plan_row["proposed_end"],
        audio_offset=plan_row.get("audio_offset") or 0.0,
        render_only=True,
        plan_id=plan_row["id"],
        config=config,
        remove_segments=remove_segments,
        generate_metadata=True,
    )
    assert applied["success"] is True, applied.get("error")
    assert applied["auto_edit_applied"] is True
    create_api.assert_not_called()
    upload.assert_not_called()

    out_dir = Path(applied["output_dir"])
    renders = sorted(out_dir.glob("*Processed*.mp4"))
    assert len(renders) == 1
    render = renders[0]
    kept = sum(b - a for a, b in kept_transcript_spans(PLAN))
    tail = min(2.0, _duration(video) - PLAN.end)
    assert abs(_duration(render) - (kept + tail)) <= 1.0

    saved_transcript = (out_dir / "transcript.txt").read_text(encoding="utf-8")
    assert saved_transcript == KEPT_TEXT
    assert "REMOVED SENTINEL" not in saved_transcript
    assert applied["transcript"] == KEPT_TEXT

    record = repo.get_sermon(sermon_id)
    assert record["content"]["transcript_text"] == " ".join(s["text"] for s in SEGMENTS)
    assert "REMOVED SENTINEL" in record["content"]["transcript_text"]

    assert "description" in seen_transcript
    assert seen_transcript["description"] == KEPT_TEXT
    assert "REMOVED SENTINEL" not in seen_transcript["description"]
    assert applied["description"] == "Sentinel description."
